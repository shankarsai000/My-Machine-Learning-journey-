"""## 🔄 Model Interoperability: ONNX
**ONNX (Open Neural Network Exchange)** is an open format to represent machine learning models.

### 💡 Why convert to ONNX?
* **Cross-Platform**: You can train a model in scikit-learn (Python) and run it in C++, C#, Java, or even JavaScript in the browser (using ONNX Runtime Web).
* **Performance**: ONNX Runtime is heavily optimized and often yields much faster inference times compared to native Python execution.

Below, we map our 30-feature input to a `FloatTensorType` and serialize the scikit-learn pipeline into `.onnx` format.
"""

import numpy as np
import joblib
from skl2onnx import convert_sklearn
from skl2onnx.common.data_types import FloatTensorType

# Load the trained pipeline from the artifact
artifact = joblib.load("artifacts/breast_cancer_model.joblib")
pipeline = artifact["model"]

initial_type = [
    ("features", FloatTensorType([None, 30]))
]

onnx_model = convert_sklearn(
    pipeline,
    initial_types=initial_type,
)

with open("artifacts/model.onnx", "wb") as file:
    file.write(onnx_model.SerializeToString())

print("ONNX model saved successfully!")

