class Generator(nn.Module):

    def __init__(self, latent_dim=100, image_dim=784):
        super().__init__()

        self.network = nn.Sequential(
            nn.Linear(latent_dim, 256),
            nn.BatchNorm1d(256),
            nn.LeakyReLU(0.2),

            nn.Linear(256, 512),
            nn.BatchNorm1d(512),
            nn.LeakyReLU(0.2),

            nn.Linear(512, image_dim),
            nn.Sigmoid()
        )

    def forward(self, z):
        return self.network(z)

class Discriminator(nn.Module):

    def __init__(self, image_dim=784):
        super().__init__()

        self.network = nn.Sequential(
            nn.Linear(image_dim, 512),
            nn.LeakyReLU(0.2),
            nn.Dropout(0.3),

            nn.Linear(512, 256),
            nn.LeakyReLU(0.2),
            nn.Dropout(0.3),

            nn.Linear(256, 1)
        )

    def forward(self, image):
        return self.network(image)

latent_dim = 100

generator = Generator(latent_dim).to(device)

discriminator = Discriminator().to(device)

criterion = nn.BCEWithLogitsLoss()

optimizer_G = torch.optim.Adam(
    generator.parameters(),
    lr=0.0002,
    betas=(0.5, 0.999)
)

optimizer_D = torch.optim.Adam(
    discriminator.parameters(),
    lr=0.0002,
    betas=(0.5, 0.999)
)

epochs = 20

for epoch in range(epochs):

    generator.train()
    discriminator.train()

    for real_images, _ in train_loader:

        batch_size = real_images.size(0)

        real_images = real_images.view(batch_size, -1).to(device)

        # Label Smoothing: target 0.9 instead of 1.0 for real images
        real_labels = torch.ones(
            batch_size, 1, device=device
        ) * 0.9

        fake_labels = torch.zeros(
            batch_size, 1, device=device
        )

        # -------------------------
        # Train Discriminator
        # -------------------------

        optimizer_D.zero_grad()

        real_logits = discriminator(real_images)

        loss_real = criterion(
            real_logits,
            real_labels
        )

        noise = torch.randn(
            batch_size, latent_dim, device=device
        )

        fake_images = generator(noise)

        fake_logits = discriminator(
            fake_images.detach()
        )

        loss_fake = criterion(
            fake_logits,
            fake_labels
        )

        loss_D = loss_real + loss_fake

        loss_D.backward()

        optimizer_D.step()

        # -------------------------
        # Train Generator
        # -------------------------

        optimizer_G.zero_grad()

        noise = torch.randn(
            batch_size, latent_dim, device=device
        )

        generated_images = generator(noise)

        generated_logits = discriminator(generated_images)

        # Generator wants D to think images are real (target 1.0)
        loss_G = criterion(
            generated_logits,
            torch.ones(batch_size, 1, device=device)
        )

        loss_G.backward()

        optimizer_G.step()

    print(
        f"Epoch [{epoch + 1}/{epochs}] "
        f"D Loss: {loss_D.item():.4f} "
        f"G Loss: {loss_G.item():.4f}"
    )

generator.eval()

