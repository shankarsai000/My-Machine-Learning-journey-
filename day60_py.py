def objective(trial):

    params = {
        "objective": "binary:logistic",
        "eval_metric": "auc",
        "tree_method": "hist",

        "max_depth": trial.suggest_int(
            "max_depth", 2, 10
        ),

        "learning_rate": trial.suggest_float(
            "learning_rate",
            0.01,
            0.3,
            log=True
        ),

        "min_child_weight": trial.suggest_float(
            "min_child_weight",
            1,
            10
        ),

        "subsample": trial.suggest_float(
            "subsample",
            0.6,
            1.0
        ),

        "colsample_bytree": trial.suggest_float(
            "colsample_bytree",
            0.6,
            1.0
        ),

        "lambda": trial.suggest_float(
            "lambda",
            1e-3,
            10.0,
            log=True
        ),

        "alpha": trial.suggest_float(
            "alpha",
            1e-3,
            10.0,
            log=True
        ),

        "seed": 42,
        "verbosity": 0,
        "nthread": -1
    }

    with mlflow.start_run(
        run_name=f"Optuna_Trial_{trial.number}"
    ) as run:

        mlflow.set_tags({
            "optimization": "Optuna",
            "sampler": "TPE",
            "model": "XGBoost",
            "trial_number": str(trial.number)
        })

        mlflow.log_params(params)

        dtrain = xgb.DMatrix(
            X_train_opt,
            label=y_train_opt
        )

        dvalid = xgb.DMatrix(
            X_valid,
            label=y_valid
        )

        pruning_callback = OptunaPruningCallback(
            trial,
            metric_name="auc"
        )

        booster = xgb.train(
            params=params,
            dtrain=dtrain,
            num_boost_round=500,

            evals=[
                (dtrain, "train"),
                (dvalid, "validation")
            ],

            early_stopping_rounds=40,

            callbacks=[
                pruning_callback
            ],

            verbose_eval=False
        )

        best_auc = float(booster.best_score)

        best_iteration = int(
            booster.best_iteration
        )

        mlflow.log_metric(
            "validation_auc",
            best_auc
        )

        mlflow.log_metric(
            "best_iteration",
            best_iteration
        )

        trial.set_user_attr(
            "best_iteration",
            best_iteration
        )

        trial.set_user_attr(
            "mlflow_run_id",
            run.info.run_id
        )

        return best_auc

