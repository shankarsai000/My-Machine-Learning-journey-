"""### Threshold Tuning for Clinical Safety
Since missing a malignant case (False Positive where Malignant=0, Benign=1 or vice versa depending on mapping; here `malignant` is class 0 and `benign` is class 1) is dangerous, let's plot the precision-recall curve and find a threshold that minimizes false positives for malignant tumors.
"""

import numpy as np
import matplotlib.pyplot as plt
from sklearn.metrics import precision_recall_curve, confusion_matrix, classification_report

# Let's inspect different threshold values
thresholds = np.linspace(0.01, 0.99, 100)
best_threshold = 0.5
min_missed_malignant = 999

# We want to minimize malignant tumors (Class 0) classified as benign (Class 1)
# With y_test (0 = malignant, 1 = benign) and predictions (test_probabilities >= threshold)
# A missed malignant case is when y_test == 0 but prediction == 1 (False Positive for Class 1)

for t in thresholds:
    preds = (test_probabilities >= t).astype(int)
    tn, fp, fn, tp = confusion_matrix(y_test, preds).ravel()
    # fp represents actual malignant (0) classified as benign (1)
    if fp < min_missed_malignant:
        min_missed_malignant = fp
        best_threshold = t
    elif fp == min_missed_malignant:
        # tie breaker: choose threshold closer to 0.5
        if abs(t - 0.5) < abs(best_threshold - 0.5):
            best_threshold = t

print(f"Recommended Optimized Threshold: {best_threshold:.4f}")

# Apply the optimized threshold
opt_predictions = (test_probabilities >= best_threshold).astype(int)

print("\nOptimized Confusion Matrix:")
new_cm = confusion_matrix(y_test, opt_predictions)
print(new_cm)
print(f"Missed Malignant Cases: {new_cm[0, 1]}")

print("\nOptimized Classification Report:")
print(classification_report(y_test, opt_predictions, target_names=data.target_names))