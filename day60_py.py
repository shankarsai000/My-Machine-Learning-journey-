class OptunaPruningCallback(xgb.callback.TrainingCallback):

    def __init__(self, trial, metric_name="auc"):
        self.trial = trial
        self.metric_name = metric_name

    def after_iteration(self, model, epoch, evals_log):

        validation_score = evals_log[
            "validation"
        ][self.metric_name][-1]

        # Report intermediate validation performance
        self.trial.report(
            validation_score,
            step=epoch
        )

        # Stop weak trials early
        if self.trial.should_prune():
            raise optuna.TrialPruned()

        return False

